import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const manifestPath = path.join(root, "sources", "rights-manifest.json");
const outputPath = path.join(root, "docs", "source-attribution.md");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

const rows = manifest.sources
  .map((source) => {
    const licence = source.licence.identifier ?? source.licence.name;
    const redistribution = source.permissions.redistribution;
    return [
      source.name,
      source.component,
      licence,
      redistribution,
      source.repository.mode,
    ];
  })
  .sort((a, b) => a[0].localeCompare(b[0]));

const lines = [
  "# External source attribution and reuse",
  "",
  "Generated from `sources/rights-manifest.json`. Do not edit this file manually.",
  "",
  "This table records the repository's current reuse decision; it is not legal advice and does not replace upstream terms.",
  "",
  "| Source | Component | Licence / terms | Redistribution | Repository policy |",
  "| --- | --- | --- | --- | --- |",
  ...rows.map(
    (row) =>
      "| " +
      row.map((cell) => String(cell).replaceAll("|", "\\|")).join(" | ") +
      " |",
  ),
  "",
  "## Attributions",
  "",
  ...manifest.sources
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((source) => [
      "### " + source.name + " (" + source.component + ")",
      "",
      source.attribution,
      "",
      "- Source: " + source.canonicalUrl,
      "- Terms/licence: " + source.licence.url,
      "- Repository policy: " + source.repository.note,
      "",
    ]),
];

const rendered = lines.join("\n") + "\n";
const check = process.argv.includes("--check");

if (check) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    console.error("Missing generated attribution document: " + outputPath);
    process.exit(1);
  }

  if (current !== rendered) {
    console.error(
      "docs/source-attribution.md is stale. Run: npm run sources:attribution",
    );
    process.exit(1);
  }

  console.log("Source attribution document is current.");
} else {
  await writeFile(outputPath, rendered, "utf8");
  console.log("Wrote " + outputPath);
}
